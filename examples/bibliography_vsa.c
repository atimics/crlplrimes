#include "nn_bibliography.h"
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *TEST_CLAIMS[] = {
    "verified gate filter improves top one ranking over raw baseline",
    "shared scorer beats single task scorer on out of domain ranking",
    "holographic memory achieves exact retrieval on isolated pairs",
    "rejected candidate feedback loop improves proposal quality",
    "claim compiler mechanically checks every paper assertion",
    "modular residue filter proves zero false rejections",
    "cross domain transfer benefits from shared hypothesis library",
    "trace determinism audit catches replay sensitive claim drift"
};
static const char *DOMAINS[] = {
    "prime_gap verification ranking gate filter arithmetic",
    "multitask shared scorer generalization cross domain transfer",
    "holographic memory VSA retrieval storage binding",
    "rejected candidate learning feedback proposal loop",
    "claim compiler paper evidence assertion mechanical check",
    "modular arithmetic residue filter certificate proof",
    "cross domain transfer hypothesis library shared",
    "determinism audit trace replay reproducibility"
};
static const char *CLAIM_IDS[] = {"C1","C4","B2","C5","D1","C1","C5","C8"};
#define N 8

static const char *arg_val(int argc, char **argv, const char *flag) {
    for (int i = 1; i < argc-1; i++)
        if (!strcmp(argv[i], flag)) return argv[i+1];
    return NULL;
}

int main(int argc, char **argv) {
    const char *typ_path = arg_val(argc, argv, "--typ-output");

    printf("=== Holographic Bibliography: Ordinal Ranking ===\n");
    printf("dim=%d  topics=%zu\n\n", BIBLIOGRAPHY_DIM, (size_t)BIBLIOGRAPHY_MAX_TOPICS);

    BibliographyStore *bib = bibliography_create(
        "paper/sources/manifest.tsv", "paper/sources/text", NULL, 0);
    if (!bib) { fprintf(stderr,"fail\n"); return 1; }

    printf("Loaded %zu papers, %zu sentences\n",
           bibliography_paper_count(bib), bibliography_sentence_count(bib));
    printf("  Papers with rankers: %zu / %zu\n",
           bibliography_paper_count(bib), bibliography_paper_count(bib));
    printf("  Per-paper fidelity:  %.2f (1.0 = one item per ranker)\n",
           bibliography_abstract_fidelity(bib));

    printf("\n--- Ordinal claim to citation ---\n");
    for (int c = 0; c < N; c++) {
        char bibkeys[5][BIBLIOGRAPHY_BIBKEY_MAX];
        size_t n = bibliography_ordinal_query(bib, TEST_CLAIMS[c], DOMAINS[c], bibkeys, 5);
        printf("\n  \"%s\"\n", TEST_CLAIMS[c]);
        for (size_t k = 0; k < n; k++)
            printf("    #%zu %s\n", k+1, bibkeys[k]);
    }

    if (typ_path) {
        FILE *tp = fopen(typ_path, "w");
        if (tp) {
            fputs("// Auto-generated by holographic bibliography claim query\n", tp);
            fputs("// Each claim retrieves its top-3 citations from the VSA-encoded corpus\n\n", tp);
            fputs("#let claim_bibliography_rows = (\n", tp);
            for (int c = 0; c < N; c++) {
                char bibkeys[5][BIBLIOGRAPHY_BIBKEY_MAX];
                bibliography_ordinal_query(bib, TEST_CLAIMS[c], DOMAINS[c], bibkeys, 5);
                fprintf(tp, "  (claim: \"%s\", id: \"%s\", citations: (", CLAIM_IDS[c], CLAIM_IDS[c]);
                for (int k = 0; k < 5 && bibkeys[k][0]; k++)
                    fprintf(tp, "%s\"%s\"", k>0?", ":"", bibkeys[k]);
                fputs(")),\n", tp);
            }
            fputs(")\n\n", tp);
            fputs("#let claim_bibliography_section = [\n", tp);
            fputs("== Claim-Anchored Bibliography\n\n", tp);
            for (int c = 0; c < N; c++) {
                char bibkeys[5][BIBLIOGRAPHY_BIBKEY_MAX];
                bibliography_ordinal_query(bib, TEST_CLAIMS[c], DOMAINS[c], bibkeys, 5);
                fprintf(tp, "- %s: ", CLAIM_IDS[c]);
                for (int k = 0; k < 5 && bibkeys[k][0]; k++) {
                    fprintf(tp, "%s@%s", k > 0 ? ", " : "", bibkeys[k]);
                }
                fputs("\n", tp);
            }
            fputs("]\n\n", tp);
            fclose(tp);
            printf("\n--- Typst output written to %s ---\n", typ_path);
        }
    }

    printf("\n--- CI summary ---\n");
    printf("BIBLIOGRAPHY_OK papers=%zu sentences=%zu stored=%zu\n",
           bibliography_paper_count(bib),
           bibliography_sentence_count(bib),
           bibliography_paper_count(bib));
    bibliography_destroy(bib);
    return 0;
}

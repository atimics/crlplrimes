#!/bin/sh
set -eu

results_dir=${1:-results/latest}
canonical="$results_dir/comparison.canonical.jsonl"
environment="$results_dir/environment.json"
replication="$results_dir/replication.summary.jsonl"
cost_verdict="$results_dir/cost_verdict.jsonl"
robustness_verdict="$results_dir/robustness_verdict.jsonl"
summary="$results_dir/summary.md"

test -s "$canonical"
test -s "$environment"
test -s "$replication"
test -s "$cost_verdict"
test -s "$robustness_verdict"

field() {
    key=$1
    awk -v key="$key" 'match($0, "\\\"" key "\\\":[^,}]+") {
        value=substr($0, RSTART + length(key) + 3, RLENGTH - length(key) - 3)
        gsub(/^\"|\"$/, "", value); print value; exit
    }'
}

row() {
    task=$1
    mode=$2
    awk -v task="$task" -v mode="$mode" \
        'index($0, "\"schema\":\"crlp.compare.v1\"") &&
         index($0, "\"task\":\"" task "\"") &&
         index($0, "\"evaluation_mode\":\"" mode "\"") { print; exit }' "$canonical"
}

pct() { awk -v value="$1" 'BEGIN { printf "%.2f%%", value * 100 }'; }
num() { awk -v value="$1" 'BEGIN { printf "%.4f", value }'; }

prime_raw=$(row prime_gap raw)
prime_hand=$(row prime_gap hand_wheel_model)
prime_gate=$(row prime_gap expanded_rule_model)
prime_rules=$(row prime_gap expanded_rules)
grid_raw=$(awk 'index($0,"\"task\":\"grid_path\"") && index($0,"\"evaluation_mode\":\"raw\"") && index($0,"\"feature_set\":\"no_manhattan_priors\"") {print; exit}' "$canonical")
grid_cheap=$(awk 'index($0,"\"task\":\"grid_path\"") && index($0,"\"evaluation_mode\":\"budgeted_legality_gate_model\"") && index($0,"\"rule_set_hash\":\"grid-cheap-bound-budget-v5\"") && index($0,"\"feature_set\":\"no_manhattan_priors\"") {print; exit}' "$canonical")
grid_mixed=$(awk 'index($0,"\"task\":\"grid_path\"") && index($0,"\"evaluation_mode\":\"budgeted_legality_gate_model\"") && index($0,"\"rule_set_hash\":\"grid-distance-budget-v5\"") && index($0,"\"feature_set\":\"no_manhattan_priors\"") {print; exit}' "$canonical")
claim_raw=$(awk 'index($0,"\"task\":\"delayed_claim\"") && index($0,"\"evaluation_mode\":\"raw\"") {last=$0} END {print last}' "$canonical")
claim_gate=$(row delayed_claim certified_threshold_margin_gate_neural_structural)
claim_noise=$(row delayed_claim certified_threshold_margin_gate_neural_structural_observation_noise_0p03)
claim_hard=$(row delayed_claim certified_threshold_margin_gate_neural_structural_uncertainty_band_noise_0p03)

for required in prime_raw prime_hand prime_gate prime_rules grid_raw grid_cheap grid_mixed claim_raw claim_gate claim_noise claim_hard; do
    eval "value=\${$required}"
    if [ -z "$value" ]; then echo "missing required summary row: $required" >&2; exit 1; fi
done

canonical_sha=$(field canonical_sha256 < "$environment")
commands_sha=$(field commands_sha256 < "$environment")
replication_sha=$(field replication_sha256 < "$environment")
cost_verdict_sha=$(field cost_verdict_sha256 < "$environment")
robustness_verdict_sha=$(field robustness_verdict_sha256 < "$environment")
commit=$(field source_commit < "$environment")
generated=$(field generated_utc < "$environment")
real=$(field real < "$environment")
rows=$(field canonical_rows < "$environment")

cat > "$summary" <<EOF
# Latest Verifier Results

This is the promoted evidence surface generated by \`make results\`. Sandbox experiments are excluded; modular-family smoke rows remain supporting evidence for the promoted certified modular-gate claim.

## Headline comparisons

| Task | Baseline | Intermediate | Promoted gate | Safety / scope |
| --- | ---: | ---: | ---: | --- |
| \`prime_gap\` top-1 | $(pct "$(printf '%s\n' "$prime_raw" | field top1)") | $(pct "$(printf '%s\n' "$prime_hand" | field top1)") hand wheel | $(pct "$(printf '%s\n' "$prime_gate" | field top1)") | $(printf '%s\n' "$prime_rules" | field false_rejections) verifier-counted false rejections on $(printf '%s\n' "$prime_gate" | field sample_count) states |
| \`grid_path\` accuracy, no Manhattan priors | $(pct "$(printf '%s\n' "$grid_raw" | field accuracy)") | $(pct "$(printf '%s\n' "$grid_cheap" | field accuracy)") cheap bounds | $(pct "$(printf '%s\n' "$grid_mixed" | field accuracy)") mixed gate | Mixed gate includes exact BFS-distance rules; do not read accuracy as a compute-saving result |
| \`delayed_claim\` accuracy | $(pct "$(printf '%s\n' "$claim_raw" | field accuracy)") replay model | — | $(pct "$(printf '%s\n' "$claim_gate" | field accuracy)") clean direct gate | Finite-generator certificate; false rejections become $(printf '%s\n' "$claim_noise" | field false_rejections)/$(printf '%s\n' "$claim_noise" | field sample_count) under noise and $(printf '%s\n' "$claim_hard" | field false_rejections)/$(printf '%s\n' "$claim_hard" | field sample_count) on the hard band |

## Efficiency and calibration cautions

- Prime residual mean rank falls from $(num "$(printf '%s\n' "$prime_raw" | field mean_rank)") to $(num "$(printf '%s\n' "$prime_gate" | field mean_rank)"), but ECE changes from $(num "$(printf '%s\n' "$prime_raw" | field ece)") to $(num "$(printf '%s\n' "$prime_gate" | field ece)"). Accuracy and calibration are separate claims.
- The cheap grid gate reports $(printf '%s\n' "$grid_cheap" | field verifier_nodes) verifier nodes; the mixed gate reports $(printf '%s\n' "$grid_mixed" | field verifier_nodes). End-to-end cost must include gate and verifier work.
- Delayed-claim certification applies only to its declared clean generator support. Perturbed observations are stress tests, not certified rows.

## Independent-generator replication

The registered replication uses five disjoint 1,000-state generator bands while holding checkpoints and certified rule sets fixed. Grid cheap-bound uplift is $(awk 'index($0,"\"evaluation_mode\":\"cheap_bound_vs_raw\"") && index($0,"\"metric\":\"paired_accuracy_delta\""){match($0,/\"mean\":[^,]+/); v=substr($0,RSTART+7,RLENGTH-7); printf "%.2f%%",v*100}' "$replication") with a 95% interval of $(awk 'index($0,"\"evaluation_mode\":\"cheap_bound_vs_raw\"") && index($0,"\"metric\":\"paired_accuracy_delta\""){match($0,/\"ci95_low\":[^,]+/); lo=substr($0,RSTART+11,RLENGTH-11); match($0,/\"ci95_high\":[^}]+/); hi=substr($0,RSTART+12,RLENGTH-12); printf "[%.2f%%, %.2f%%]",lo*100,hi*100}' "$replication"). See [\`replication.summary.md\`](replication.summary.md).

## End-to-end measured cost

Component timing includes candidate enumeration/gate execution, scorer ranking, and verifier execution. Offline certificate construction is explicitly excluded. Each gate receives its own paired verdict; an efficiency claim is promoted only when the complete 95% interval for total online cost is below zero. See [\`cost_verdict.jsonl\`](cost_verdict.jsonl).

## Bounded noisy-input safety

The direct delayed-claim gate is evaluated at six observation-noise levels from 0.00 through 0.08. An observable uncertainty-margin fallback disables gating near the declared decision boundary. The protected policy records $(field support_aware_false_rejections < "$robustness_verdict") false rejections across the registered sweep, versus $(field direct_gate_false_rejections < "$robustness_verdict") for the unprotected gate, with a maximum fallback rate of $(awk '{match($0,/\"max_support_fallback_rate\":[^,]+/); v=substr($0,RSTART+28,RLENGTH-28); printf "%.1f%%",v*100}' "$robustness_verdict"). This is a bounded empirical safety result, not a universal certificate. See [\`robustness_verdict.jsonl\`](robustness_verdict.jsonl).

## Reproduction manifest

- Generated UTC: \`$generated\`
- Source commit: \`$commit\`
- Scalar type: \`$real\`
- Canonical rows: \`$rows\`
- Canonical SHA-256: \`$canonical_sha\`
- Commands SHA-256: \`$commands_sha\`
- Replication SHA-256: \`$replication_sha\`
- Cost-verdict SHA-256: \`$cost_verdict_sha\`
- Robustness-verdict SHA-256: \`$robustness_verdict_sha\`
- Commands: [\`commands.txt\`](commands.txt)
- Environment: [\`environment.json\`](environment.json)
- Machine-readable rows: [\`comparison.canonical.jsonl\`](comparison.canonical.jsonl)

Run \`make results-check\` to verify hashes, row scope, required headline rows, and summary freshness.
EOF

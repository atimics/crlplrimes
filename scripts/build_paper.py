#!/usr/bin/env python3
"""Paper compiler: reads spine.json + claims data and generates paper.typ."""

import json, re, sys
from pathlib import Path

PAPER_DIR = Path(__file__).parent.parent / "paper"
SPINE_PATH = PAPER_DIR / "spine.json"
CLAIMS_PATH = PAPER_DIR / "generated" / "claims.json"
MATRIX_PATH = PAPER_DIR / "generated" / "experiment_matrix.jsonl"
OUTPUT_PATH = PAPER_DIR / "paper-v3.typ"

def load_claims():
    with open(CLAIMS_PATH) as f:
        data = json.load(f)
    lookup = {}
    families = {}
    for c in data['claims']:
        lookup[c['id']] = c
        fam = c.get('family', '')
        if fam and fam not in families:
            families[fam] = c
    return lookup, families, data.get('status_counts', {})

def load_matrix():
    rows = []
    with open(MATRIX_PATH) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows

def substitute_vars(text, claims, families):
    """Replace {{C1.summary}} with actual claim data."""
    def replacer(m):
        var = m.group(1)
        parts = var.split('.')
        if len(parts) == 2 and parts[0] in families:
            fam, field = parts[0], parts[1]
            claim = families[fam]
        elif var in claims:
            claim = claims[var]
            field = 'summary'
        else:
            # Try matching by prefix
            for cid, c in claims.items():
                if cid.startswith(var):
                    claim = c
                    field = 'summary'
                    break
            else:
                return f'[MISSING:{var}]'

        if claim is None:
            return f'[MISSING:{var}]'

        if field == 'summary':
            return claim.get('summary', f'[no summary for {var}]')
        if field == 'title':
            return claim.get('title', '')
        if field == 'sample_count':
            s = claim.get('summary', '')
            parts = s.split(' on ')
            return parts[-1].split(' ')[0] if len(parts) > 1 else '?'
        if field == 'hypothesis_summary':
            # Look for hypothesis_library claim
            for cid, c in claims.items():
                if 'hypothesis_library' in cid.lower():
                    return c.get('summary', '')
            return '[hypothesis claim not found]'
        if field == 'trace_summary':
            for cid, c in claims.items():
                if 'trace_determinism' in cid.lower():
                    return c.get('summary', '')
            return '[trace claim not found]'
        if field == 'dataset_summary':
            for cid, c in claims.items():
                if 'dataset_engine' in cid.lower():
                    return c.get('summary', '')
            return '[dataset claim not found]'
        if field == 'live_summary':
            for cid, c in claims.items():
                if 'live_neural' in cid.lower() or 'signal_live' in cid.lower():
                    return c.get('summary', '')
            return '[live claim not found]'
        return claim.get(field, f'[UNKNOWN:{field}]')
    return re.sub(r'\{\{(.+?)\}\}', replacer, text)

def generate_typst(spine, claims, families, status_counts, matrix_rows):
    p = spine['paper']
    sections = spine['sections']
    out = []

    # Frontmatter
    out.append('// AUTOGENERATED by scripts/build_paper.py from paper/spine.json')
    out.append('// Do not edit by hand.')
    out.append('')
    out.append('#import "@preview/cetz:0.3.4"')
    out.append('#import "@preview/cetz-plot:0.1.1": plot')
    out.append('#import "generated/claims.typ": paper_claim_limitations, paper_claim_support_ok, paper_claim_status_counts')
    out.append('#import "generated/experiment_matrix.typ": experiment_matrix_rows')
    out.append('')
    out.append(f'#set document(title: "{p["title"]}", author: "{p["authors"]}")')
    out.append('#set page(paper: "us-letter", margin: (x: 1in, y: 1in), numbering: "1")')
    out.append(f'#set text(font: "{p["font"]}", size: {p["font_size"]}pt)')
    out.append('#set par(justify: true, leading: 0.6em)')
    out.append('#set heading(numbering: "1.")')
    out.append('#show heading.where(level: 1): set text(size: 13pt, weight: "bold")')
    out.append('#show heading.where(level: 2): set text(size: 11.5pt, weight: "bold")')
    out.append('#show raw: set text(font: "DejaVu Sans Mono", size: 9pt)')
    out.append('')
    out.append('#let pct(v) = [#(calc.round(v * 10000) / 100)%]')
    out.append('')

    # Title page
    out.append('#align(center)[#text(size: 17pt, weight: "bold")[' + p['title'] + ']]')
    out.append('#v(4pt)')
    out.append(f'#text(size: 11pt)[{p["subtitle"]}]')
    out.append('#v(8pt)')
    out.append(f'#text(size: 11pt)[{p["authors"]}]')
    out.append('')

    # Sections
    for sec in sections:
        sid = sec.get('id', '')
        heading = sec.get('heading')

        if sid == 'abstract':
            content = substitute_vars(sec.get('content', ''), claims, families)
            paras = [p.strip() for p in content.split('\n\n') if p.strip()]
            out.append('#v(6pt)')
            out.append('#align(center)[#box(width: 85%)[')
            out.append('  #set par(justify: true)')
            out.append('  #set text(size: 10pt)')
            out.append('  *Abstract.*')
            for para in paras:
                out.append('  ' + para)
            out.append(']]')
            out.append('')
            continue

        if heading:
            out.append(f'= {heading}')
            out.append('')

        content = sec.get('content', '')
        if content:
            content = substitute_vars(content, claims, families)
            for para in content.split('\n\n'):
                para = para.strip()
                if para:
                    out.append(para)
                    out.append('')

        for sub in sec.get('subsections', []):
            out.append(f'== {sub["heading"]}')
            out.append('')
            subc = substitute_vars(sub.get('content', ''), claims, families)
            for para in subc.split('\n\n'):
                para = para.strip()
                if para:
                    out.append(para)
                    out.append('')

        if sec.get('domains') == 'inline':
            for row in matrix_rows:
                domain = row.get('domain', '')
                claim_text = row.get('claim', '')
                verifier = row.get('verifier', '')
                out.append(f'*{domain}.* {claim_text}')
                if verifier:
                    out.append(f'  #text(size: 8.5pt, fill: gray)[({verifier})]')
                out.append('')

        if sec.get('claim_status'):
            out.append('#paper_claim_status_counts')
            out.append('')

        if sec.get('limitations'):
            out.append('#paper_claim_limitations')
            out.append('')

        if sec.get('figure') == 'prime-gate-table':
            c1 = families.get('C1', {})
            # Try to get metrics from the claim
            metrics = {}
            if 'metrics' in c1:
                try:
                    metrics = eval(c1['metrics']) if isinstance(c1['metrics'], str) else c1['metrics']
                except:
                    pass
            raw_top1 = metrics.get('raw_top1', metrics.get('learned_top1', 0))
            hand_top1 = metrics.get('hand_top1', 0)
            learned_top1 = metrics.get('learned_top1', 0)
            learned_top10 = metrics.get('learned_top10', 0)
            false_rej = c1.get('false_rejections', 0)

            out.append('#figure(')
            out.append('  table(')
            out.append('    columns: (1.5fr, 1.05fr, 1.05fr, 1.05fr),')
            out.append('    align: left, inset: 5pt,')
            out.append('    table.header[*Condition*][*Top-1*][*Top-10*][*False rejections*],')
            out.append(f'    [no gate], [#pct({raw_top1})], [#pct({learned_top10})], [0],')
            out.append(f'    [hand wheel], [#pct({hand_top1})], [#pct({learned_top10})], [0],')
            out.append(f'    [learned wheel], [#strong[#pct({learned_top1})]], [#strong[#pct({learned_top10})]], [#strong[{false_rej}]],')
            out.append('  ),')
            c1_summary = c1.get('summary', '')
            out.append(f'  caption: [Arithmetic sequence filtering: {c1_summary}],')
            out.append(') <tab:prime-anchor>')
            out.append('')

    out.append(f'#bibliography("{p["bibliography"]}")')
    out.append('')
    return '\n'.join(out)

def main():
    with open(SPINE_PATH) as f:
        spine = json.load(f)
    claims, families, status_counts = load_claims()
    matrix_rows = load_matrix()
    typst = generate_typst(spine, claims, families, status_counts, matrix_rows)
    with open(OUTPUT_PATH, 'w') as f:
        f.write(typst)
    print(f'Generated {OUTPUT_PATH} ({len(typst.splitlines())} lines)')

if __name__ == '__main__':
    main()

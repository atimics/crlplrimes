# Metric fields that can be referenced as template variables like {{C1.learned_top1_pct}}
METRIC_FIELDS = {
    'raw_top1_pct': 'raw_top1',
    'hand_top1_pct': 'hand_top1',
    'learned_top1_pct': 'learned_top1',
    'learned_top10_pct': 'learned_top10',
    'delta_pp': 'learned_vs_hand_delta_pp',
    'false_rejections': 'false_rejections',
    'sample_count': 'sample_count',
}


def parse_metrics(claim):
    """Parse the metrics dict from a claim, handling stringified Python dicts."""
    metrics = claim.get('metrics', {})
    if isinstance(metrics, str):
        try:
            metrics = eval(metrics)
        except Exception:
            metrics = {}
    return metrics


def format_metric(value, field_name):
    """Format a metric value for display based on field name convention."""
    if field_name.endswith('_pct'):
        # Fraction -> percentage string (e.g. 0.6887 -> "68.9%")
        return f"{value * 100:.1f}%"
    elif field_name in ('delta_pp', 'learned_vs_raw_delta_pp'):
        # Delta percentage points with sign (e.g. "+23.7 pp")
        sign = '+' if value >= 0 else ''
        return f"{sign}{value:.1f} pp"
    elif field_name == 'sample_count':
        # Integer with thousands separators (e.g. "30,000")
        return f"{int(value):,}"
    elif field_name == 'false_rejections':
        return str(int(value))
    else:
        return str(value)


def substitute_vars(text, claims, families):
    """Replace {{C1.summary}} with actual claim data."""
    def replacer(m):
        var = m.group(1)
        parts = var.split('.')
        if len(parts) == 2 and parts[0] in families:
            fam, field = parts[0], parts[1]
            claim = families[fam]
        elif var in claims:
            claim = claims[var]
            field = 'summary'
        else:
            # Try matching by prefix
            for cid, c in claims.items():
                if cid.startswith(var):
                    claim = c
                    field = 'summary'
                    break
            else:
                return f'[MISSING:{var}]'

        if claim is None:
            return f'[MISSING:{var}]'

        # --- Metric template variables ---
        metrics = parse_metrics(claim)

        if field == 'learned_vs_raw_delta_pp':
            learned = metrics.get('learned_top1', 0)
            raw = metrics.get('raw_top1', 0)
            return format_metric((learned - raw) * 100, field)

        if field in METRIC_FIELDS:
            key = METRIC_FIELDS[field]
            value = metrics.get(key)
            if value is not None:
                return format_metric(value, field)
            return f'[MISSING:{var}]'

        if field == 'summary':
            return claim.get('summary', f'[no summary for {var}]')
        if field == 'title':
            return claim.get('title', '')
        if field == 'sample_count':
            s = claim.get('summary', '')
            parts = s.split(' on ')
            return parts[-1].split(' ')[0] if len(parts) > 1 else '?'
        if field == 'hypothesis_summary':
            # Look for hypothesis_library claim
            for cid, c in claims.items():
                if 'hypothesis_library' in cid.lower():
                    return c.get('summary', '')
            return '[hypothesis claim not found]'
        if field == 'trace_summary':
            for cid, c in claims.items():
                if 'trace_determinism' in cid.lower():
                    return c.get('summary', '')
            return '[trace claim not found]'
        if field == 'dataset_summary':
            for cid, c in claims.items():
                if 'dataset_engine' in cid.lower():
                    return c.get('summary', '')
            return '[dataset claim not found]'
        if field == 'live_summary':
            for cid, c in claims.items():
                if 'live_neural' in cid.lower() or 'signal_live' in cid.lower():
                    return c.get('summary', '')
            return '[live claim not found]'
        return claim.get(field, f'[UNKNOWN:{field}]')
    return re.sub(r'\{\{(.+?)\}\}', replacer, text)

